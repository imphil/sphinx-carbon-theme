// Build the theme's static assets from the Carbon npm packages.
//
// This runs when the theme is built (in CI, or by the hatch build hook),
// never during a user's documentation build. Output goes into the theme
// directory and is git-ignored but shipped in the wheel.
//
// Usage: node scripts/build.mjs [--watch]

import * as esbuild from "esbuild";
import * as sass from "sass";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const watching = process.argv.includes("--watch");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nodeModules = path.join(root, "node_modules");
const themeDir = path.join(root, "src/sphinx_carbon_theme/theme/carbon");
const staticDir = path.join(themeDir, "static");
const iconDir = path.join(themeDir, "partials/icons");

// Carbon icons used by the templates (name in @carbon/icons/svg/32).
const ICONS = [
  "search",
  "light",
  "asleep",
  "contrast",
  "logo--github",
  "arrow--left",
  "arrow--right",
  "chevron--down",
];

// Carbon icons used from CSS (as masks), emitted as a generated Sass map.
const CSS_ICONS = [
  "information--filled",
  "checkmark--filled",
  "warning--alt--filled",
  "error--filled",
  "idea",
  "link",
];
const generatedSassDir = path.join(root, "build/sass");

// IBM Plex faces to ship: [package, file stem, weight, style].
const FONTS = [
  ["plex-sans", "IBMPlexSans-Light", 300, "normal"],
  ["plex-sans", "IBMPlexSans-Regular", 400, "normal"],
  ["plex-sans", "IBMPlexSans-Italic", 400, "italic"],
  ["plex-sans", "IBMPlexSans-SemiBold", 600, "normal"],
  ["plex-sans", "IBMPlexSans-SemiBoldItalic", 600, "italic"],
  ["plex-mono", "IBMPlexMono-Regular", 400, "normal"],
  ["plex-mono", "IBMPlexMono-Italic", 400, "italic"],
  ["plex-mono", "IBMPlexMono-SemiBold", 600, "normal"],
];

function log(msg) {
  console.log(`[carbon-sphinx] ${msg}`);
}

async function buildScripts() {
  // Start clean so stale files (e.g. source maps from watch mode) never ship.
  if (!watching) fs.rmSync(path.join(staticDir, "scripts"), { recursive: true, force: true });
  await esbuild.build({
    entryPoints: [path.join(root, "assets/scripts/carbon-sphinx.js")],
    outfile: path.join(staticDir, "scripts/carbon-sphinx.js"),
    bundle: true,
    format: "esm",
    minify: true,
    sourcemap: watching ? "linked" : false,
    target: ["es2021"],
    legalComments: "linked",
    logLevel: "warning",
  });
  log("scripts built");
}

function generateIconSass() {
  let scss = "// Generated by scripts/build.mjs from @carbon/icons. Do not edit.\n$icons: (\n";
  for (const name of CSS_ICONS) {
    const src = path.join(nodeModules, "@carbon/icons/svg/32", `${name}.svg`);
    const svg = fs.readFileSync(src, "utf8").trim().replace(/^<\?xml[^>]*>\s*/, "");
    scss += `  "${name}": url("data:image/svg+xml,${encodeURIComponent(svg)}"),\n`;
  }
  scss += ");\n";
  fs.mkdirSync(generatedSassDir, { recursive: true });
  fs.writeFileSync(path.join(generatedSassDir, "_carbon-icons.scss"), scss);
}

function buildStyles() {
  generateIconSass();
  const out = path.join(staticDir, "styles/carbon-sphinx.css");
  const result = sass.compile(path.join(root, "assets/styles/carbon-sphinx.scss"), {
    loadPaths: [nodeModules, generatedSassDir],
    style: "compressed",
    sourceMap: false,
    quietDeps: true,
  });
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, result.css);
  log(`styles built (${(result.css.length / 1024).toFixed(0)} KiB)`);
}

function copyFonts() {
  const out = path.join(staticDir, "fonts");
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  let css = "";
  for (const [pkg, stem, weight, style] of FONTS) {
    const src = path.join(nodeModules, "@ibm", pkg, "fonts/complete/woff2", `${stem}.woff2`);
    fs.copyFileSync(src, path.join(out, `${stem}.woff2`));
    const family = pkg === "plex-sans" ? "IBM Plex Sans" : "IBM Plex Mono";
    css +=
      `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};` +
      `font-display:swap;src:url("${stem}.woff2") format("woff2")}\n`;
  }
  fs.writeFileSync(path.join(out, "plex.css"), css);
  fs.copyFileSync(
    path.join(nodeModules, "@ibm/plex-sans/LICENSE.txt"),
    path.join(out, "LICENSE-IBM-Plex.txt"),
  );
  log(`fonts copied (${FONTS.length} faces)`);
}

function copyIcons() {
  fs.rmSync(iconDir, { recursive: true, force: true });
  fs.mkdirSync(iconDir, { recursive: true });
  for (const name of ICONS) {
    const src = path.join(nodeModules, "@carbon/icons/svg/32", `${name}.svg`);
    let svg = fs.readFileSync(src, "utf8").trim();
    svg = svg.replace(/^<\?xml[^>]*>\s*/, "");
    // Size via CSS; make the icon inherit text colour and hide it from AT.
    svg = svg.replace(
      /^<svg /,
      '<svg width="20" height="20" fill="currentColor" aria-hidden="true" focusable="false" ',
    );
    fs.writeFileSync(path.join(iconDir, `${name}.svg`), svg + "\n");
  }
  log(`icons copied (${ICONS.length})`);
}

async function buildAll() {
  fs.mkdirSync(staticDir, { recursive: true });
  await buildScripts();
  buildStyles();
  copyFonts();
  copyIcons();
}

async function watch() {
  await buildAll();
  log("watching assets/ for changes");
  let pending = null;
  fs.watch(path.join(root, "assets"), { recursive: true }, (_event, file) => {
    clearTimeout(pending);
    pending = setTimeout(async () => {
      try {
        if (file?.endsWith(".scss")) buildStyles();
        else await buildScripts();
      } catch (err) {
        console.error(err.message ?? err);
      }
    }, 100);
  });
}

if (watching) {
  await watch();
} else {
  await buildAll();
}
